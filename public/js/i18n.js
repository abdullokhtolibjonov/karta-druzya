export const LANGS = ['uz', 'en'];
let lang = LANGS.includes(prefs.get('lang')) ? prefs.get('lang') : 'uz';

export const getLang = () => lang;
export function setLang(l) {
  lang = l;
  prefs.set('lang', l);
  document.documentElement.lang = l;
}

export function t(key, params = {}) {
  const v = dict[lang][key] ?? dict.uz[key] ?? key;
  if (typeof v !== 'string') return v;
  return v.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ''));
}

export const tErr = (code) => t('err_' + code);

// Fill static elements: data-i18n="key" (textContent), data-i18n-ph="key" (placeholder).
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute('aria-label', el.title);
  });
}
